export function getBlogCardTitle(post: { title: string; sourceId: string; cardTitle?: string }) {
  const explicit = post.cardTitle?.trim();
  if (explicit) return explicit;
  if (Object.hasOwn(cardTitles, post.sourceId)) return cardTitles[post.sourceId];

  // Future posts can supply cardTitle. Until then, keep their core Seoul phrase
  // rather than repeating a long introductory sentence on every card.
  const title = post.title.trim();
  const seoul = title.lastIndexOf("서울");
  const core = (seoul >= 0 ? title.slice(seoul) : title.split(/[,，:：]\s*/u).at(-1) || title)
    .replace(/\s+/gu, " ")
    .trim();
  const characters = Array.from(core);
  if (characters.length <= 28) return core;
  const excerpt = characters.slice(0, 27).join("");
  const wordEnd = excerpt.lastIndexOf(" ");
  return `${wordEnd >= 16 ? excerpt.slice(0, wordEnd) : excerpt}…`;
}
